    private void inserirBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_inserirBtnActionPerformed
        // TODO add your handling code here:
        String rm;
        String nome;
        int idade;

        rm = rm_textfield.getText();
        nome = nome_textfields.getText();
        idade = Integer.parseInt(idade_textfields.getText());

        String sql = "INSERT INTO tb_alunos (rm_aluno, nm_aluno, nr_idade) values (?, ?, ?)";

        try (Connection conn = Conexao.conectar()) {
            PreparedStatement mensagem = conn.prepareStatement(sql);
            mensagem.setString(1, rm);
            mensagem.setString(2, nome);
            mensagem.setString(3, String.valueOf(idade));
            mensagem.executeUpdate();
        } catch (SQLException e) {
            throw new RuntimeException("Erro ao conectar! ", e);
        }
    }//GEN-LAST:event_inserirBtnActionPerformed

    private void editarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editarBtnActionPerformed
        // TODO add your handling code here:
        String rm;
String nome;
int idade;

rm = rm_textfield.getText();
nome = nome_textfields.getText();
idade = Integer.parseInt(idade_textfields.getText());

String sql = "UPDATE tb_alunos SET nm_aluno = ?, nr_idade = ? WHERE rm_aluno = ?";

try (Connection conn = Conexao.conectar()) {
    PreparedStatement mensagem = conn.prepareStatement(sql);
    
    mensagem.setString(1, nome);  
    mensagem.setInt(2, idade);     
    mensagem.setString(3, rm);     
    
    mensagem.executeUpdate();
    System.out.println("Aluno atualizado com sucesso!");
    
} catch (SQLException e) {
    throw new RuntimeException("Erro ao conectar ou atualizar! ", e);
}
    }//GEN-LAST:event_editarBtnActionPerformed

